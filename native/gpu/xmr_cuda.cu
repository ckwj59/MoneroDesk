static thread_local char error_message[256] = {};
static bool checked(cudaError_t error) {
    if (error==cudaSuccess) return true;
    std::snprintf(error_message,sizeof(error_message),"%s",cudaGetErrorString(error));
    return false;
}
struct Context {
    int device=0;
    uint32_t batch=0;
    std::atomic<bool> cancelled{false};
    void *dataset=nullptr,*scratch=nullptr,*hashes=nullptr,*entropy=nullptr,*states=nullptr,*rounding=nullptr,*cycles=nullptr,*reference=nullptr;
    ~Context() {
        cudaSetDevice(device);
        for (void *p : {dataset,scratch,hashes,entropy,states,rounding,cycles,reference}) if (p) cudaFree(p);
    }
};
API const char *xmr_cuda_error() { return error_message; }
API void xmr_cuda_free(void *ptr) { delete static_cast<Context*>(ptr); }
API void xmr_cuda_cancel(void *ptr,int value) { if(ptr)static_cast<Context*>(ptr)->cancelled.store(value!=0); }
API void *xmr_cuda_create(int device,const void *dataset,size_t dataset_size,uint32_t batch) {
    constexpr size_t expected=static_cast<size_t>(RANDOMX_DATASET_BASE_SIZE)+RANDOMX_DATASET_EXTRA_SIZE;
    if (!dataset || dataset_size!=expected || batch<32 || batch>1024 || batch%32) {
        std::snprintf(error_message,sizeof(error_message),"Invalid dataset or batch size");return nullptr;
    }
    Context *c=new(std::nothrow) Context();
    if (!c) return nullptr;
    c->device=device;c->batch=batch;
    if (!checked(cudaSetDevice(device)) ||
        !checked(cudaMalloc(&c->dataset,dataset_size)) ||
        !checked(cudaMemcpy(c->dataset,dataset,dataset_size,cudaMemcpyHostToDevice)) ||
        !checked(cudaMalloc(&c->scratch,static_cast<size_t>(batch)*(RANDOMX_SCRATCHPAD_L3+64))) ||
        !checked(cudaMalloc(&c->hashes,static_cast<size_t>(batch)*HASH_SIZE)) ||
        !checked(cudaMalloc(&c->entropy,static_cast<size_t>(batch)*ENTROPY_SIZE)) ||
        !checked(cudaMalloc(&c->states,static_cast<size_t>(batch)*VM_STATE_SIZE)) ||
        !checked(cudaMalloc(&c->rounding,static_cast<size_t>(batch)*sizeof(uint32_t))) ||
        !checked(cudaMalloc(&c->cycles,sizeof(uint64_t))) ||
        !checked(cudaMalloc(&c->reference,static_cast<size_t>(batch)*256*sizeof(RefInstruction)))) { delete c;return nullptr; }
    return c;
}
// Initial Blake2b-512 values are generated by the host. The expensive AES,
// scratchpad and complete RandomX VM execution below run on the selected GPU.
API int xmr_cuda_hash(void *ptr,const void *initial_hashes,size_t input_size,void *output,size_t output_size) {
    Context *c=static_cast<Context*>(ptr);
    if (!c || !initial_hashes || !output || input_size!=static_cast<size_t>(c->batch)*64 || output_size!=static_cast<size_t>(c->batch)*32) return 0;
    const uint32_t n=c->batch;
    if (!checked(cudaSetDevice(c->device)) ||
        !checked(cudaMemcpy(c->hashes,initial_hashes,input_size,cudaMemcpyHostToDevice)) ||
        !checked(cudaMemset(c->cycles,0,sizeof(uint64_t))) ||
        !checked(cudaMemset(c->rounding,0,n*sizeof(uint32_t)))) return 0;
    fillAes1Rx4<RANDOMX_SCRATCHPAD_L3,false,64><<<n/32,128>>>(c->hashes,c->scratch,n);
    if (!checked(cudaGetLastError())) return 0;
    for (unsigned program=0;program<RANDOMX_PROGRAM_COUNT;++program) {
        if(c->cancelled.load())return 2;
        fillAes4Rx4<ENTROPY_SIZE,false><<<n/32,128>>>(c->hashes,c->entropy,n);
        if (!checked(cudaGetLastError())) return 0;
        cooperative_vm<<<n/(XMR_VM_THREADS/XMR_VM_LANES),XMR_VM_THREADS>>>(c->entropy,c->states,c->scratch,c->dataset,c->rounding,(RefInstruction*)c->reference,RANDOMX_PROGRAM_ITERATIONS);
        if (!checked(cudaGetLastError())) return 0;
        if (!checked(cudaDeviceSynchronize()))return 0;
        if(c->cancelled.load())return 2;
        if (program+1==RANDOMX_PROGRAM_COUNT) {
            hashAes1Rx4<RANDOMX_SCRATCHPAD_L3,192,VM_STATE_SIZE,64><<<n/32,128>>>(c->scratch,c->states,n);
            if (!checked(cudaGetLastError())) return 0;
            blake2b_hash_registers<REGISTERS_SIZE,VM_STATE_SIZE,32><<<n/32,32>>>(c->hashes,c->states);
        } else {
            blake2b_hash_registers<REGISTERS_SIZE,VM_STATE_SIZE,64><<<n/32,32>>>(c->hashes,c->states);
        }
        if (!checked(cudaGetLastError())) return 0;
    }
    return checked(cudaDeviceSynchronize()) && checked(cudaMemcpy(output,c->hashes,output_size,cudaMemcpyDeviceToHost));
}

// Development diagnostics: compare individual stages to the CPU reference VM.
#ifdef XMR_CUDA_DIAGNOSTICS
class DebugVm : public randomx::CompiledVmHardAes {
public:
    DebugVm() : randomx::CompiledVmHardAes(static_cast<randomx_flags>(RANDOMX_FLAG_JIT | RANDOMX_FLAG_HARD_AES | RANDOMX_FLAG_FULL_MEM)) {}
    void runSteps(void *seed,unsigned count) {
        generateProgram(seed);
        initialize();
        compiler.generateProgram(program,config);
        mem.memory=datasetPtr->memory+datasetOffset;
        compiler.getProgramFunc()(reg,mem,scratchpad,count);
    }
};
API void *xmr_debug_create(void *dataset) {
    auto *vm=new DebugVm();vm->setDataset(static_cast<randomx_dataset*>(dataset));vm->allocate();return vm;
}
static unsigned debug_iterations=RANDOMX_PROGRAM_ITERATIONS;
API void xmr_debug_iterations(unsigned count) { debug_iterations=count; }
API int xmr_debug_cpu(void *machine,void *seed,void *scratch,void *registers,void *program,int stage) {
    if (!machine || !seed || !scratch) return 0;
    randomx_vm *vm=static_cast<randomx_vm*>(machine);
    if (stage==0) vm->initScratchpad(seed);
    else {
        if (stage==1) vm->resetRoundingMode();
        static_cast<DebugVm*>(vm)->runSteps(seed,debug_iterations);
        std::memcpy(registers,vm->getRegisterFile(),256);
        std::memcpy(program,&vm->getProgram(),ENTROPY_SIZE);
    }
    std::memcpy(scratch,vm->getScratchpad(),RANDOMX_SCRATCHPAD_L3);
    return 1;
}
API int xmr_debug_gpu(void *ptr,void *initial,void *updated,void *scratch,void *registers,void *program,int stage) {
    Context *c=static_cast<Context*>(ptr);if(!c)return 0;
    const uint32_t n=c->batch;
    if (stage==0) {
        if(!checked(cudaMemcpy(c->hashes,initial,n*64,cudaMemcpyHostToDevice)))return 0;
        fillAes1Rx4<RANDOMX_SCRATCHPAD_L3,false,64><<<n/32,128>>>(c->hashes,c->scratch,n);
    } else {
        if (stage==1) cudaMemset(c->rounding,0,n*sizeof(uint32_t));
        else blake2b_hash_registers<REGISTERS_SIZE,VM_STATE_SIZE,64><<<n/32,32>>>(c->hashes,c->states);
        cudaMemset(c->cycles,0,sizeof(uint64_t));
        fillAes4Rx4<ENTROPY_SIZE,false><<<n/32,128>>>(c->hashes,c->entropy,n);
        reference_vm<<<n/32,32>>>(c->entropy,c->states,c->scratch,c->dataset,c->rounding,(RefInstruction*)c->reference,debug_iterations);
        if (!checked(cudaMemcpy(registers,c->states,256,cudaMemcpyDeviceToHost)) ||
            !checked(cudaMemcpy(program,c->entropy,ENTROPY_SIZE,cudaMemcpyDeviceToHost)))return 0;
    }
    return checked(cudaGetLastError()) && checked(cudaDeviceSynchronize()) &&
        checked(cudaMemcpy(updated,c->hashes,64,cudaMemcpyDeviceToHost)) &&
        checked(cudaMemcpy(scratch,c->scratch,RANDOMX_SCRATCHPAD_L3,cudaMemcpyDeviceToHost));
}
